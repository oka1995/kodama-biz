```
【商品名】
・メルカリ相場：〇〇円〜〇〇円
・業者買取価格：〇〇円〜〇〇円
・仕入れ推奨上限：〇〇円（粗利20%確保ライン）
・注意事項：（在庫状況・季節変動など）
